/** Validate names interpolated into analysis WGSL before constructing resources. @internal */
export function validateWGSLIdentifier(id: string, name: string, identifier: string): void {
  if (
    !/^[_\p{XID_Start}][\p{XID_Continue}]*$/u.test(identifier) ||
    identifier === '_' ||
    identifier.startsWith('__') ||
    WGSL_KEYWORDS.has(identifier) ||
    WGSL_RESERVED_WORDS.has(identifier)
  ) {
    throw new Error(`${id} ${name} must be a nonreserved WGSL identifier, received ${identifier}`);
  }
}
