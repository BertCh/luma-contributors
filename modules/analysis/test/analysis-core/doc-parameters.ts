/**
 * Prefer exact class headings across all pages, then partial headings, then prose mentions.
 * Ambiguous owners require an explicit class/page/heading declaration.
 */
function findClassHeading(
  className: string,
  headingsByPage: Map<string, DocHeading[]>,
  linesByPage: Map<string, string[]>,
  owners: Readonly<Record<string, ClassDocumentationOwner>>
): DocHeading | null {
  const pattern = new RegExp(`\\b${className}\\b`, 'g');
  const candidates = [...headingsByPage].filter(
    ([page]) => !INDEX_PAGES.has(page) && !page.endsWith('-lenses.md')
  );
  const normalizeHeading = (text: string): string => text.replace(/`/g, '').trim();
  const headings = candidates
    .flatMap(([, pageHeadings]) => pageHeadings)
    .filter(heading => !/ parameters$/.test(heading.text));
  const exact = headings.filter(heading => normalizeHeading(heading.text) === className);
  const partial = headings.filter(heading => heading.text.match(pattern));
  const selectOwner = (matches: DocHeading[]): DocHeading | null => {
    const owner = owners[className];
    if (owner) {
      const declared = matches.filter(
        candidate =>
          candidate.page === owner.page &&
          normalizeHeading(candidate.text) === normalizeHeading(owner.heading)
      );
      if (declared.length > 1 && owner.occurrence === undefined) {
        throw new Error(`ambiguous declared documentation owner for ${className}`);
      }
      const heading = declared[owner.occurrence ?? 0];
      if (!heading)
        throw new Error(
          `invalid documentation owner for ${className}: ${owner.page}#${owner.heading}`
        );
      return heading;
    }
    if (matches.length > 1) {
      throw new Error(
        `ambiguous documentation owner for ${className}: ${matches.map(heading => `${heading.page}#${heading.text}`).join(', ')}`
      );
    }
    return matches[0] ?? null;
  };
  if (exact.length || partial.length) return selectOwner(exact.length ? exact : partial);
  const mentions: {heading: DocHeading; count: number}[] = [];
  for (const [page, headings] of candidates) {
    const lines = linesByPage.get(page) ?? [];
    headings.forEach((heading, index) => {
      const end = headings[index + 1]?.line ?? lines.length;
      // Table rows are indexes (comparison tables), not documentation.
      const count = lines
        .slice(heading.line + 1, end)
        .filter(line => !line.trimStart().startsWith('|'))
        .reduce((total, line) => total + (line.match(pattern)?.length ?? 0), 0);
      if (count > 0) mentions.push({heading, count});
    });
  }
  const maximum = Math.max(0, ...mentions.map(mention => mention.count));
  return selectOwner(
    mentions.filter(mention => mention.count === maximum).map(mention => mention.heading)
  );
}

/**
 * Resolves canonical class sections afresh after removing all generated blocks. Reinsert exactly
 * one block per class under its owner, repairing duplicates and misplaced blocks on every run.
 * Also returns classes for which no documentation section exists.
 */
export function generateDocPages(
  classParameters = collectClassParameters(),
  sourcePages = new Map(ANALYSIS_DOC_PAGES.map(page => [page, readDocPage(page)])),
  owners: Readonly<Record<string, ClassDocumentationOwner>> = CLASS_DOCUMENTATION_OWNERS
): {pages: Map<string, string>; undocumented: string[]} {
  const linesByPage = new Map<string, string[]>(
    [...sourcePages].map(([page, text]) => [page, removeParameterBlocks(text.split('\n'))])
  );
  const headingsByPage = new Map(
    [...linesByPage].map(([page, lines]) => [page, getHeadings(page, lines)])
  );
  const undocumented: string[] = [];
  // Insertions per page: line index → blocks, applied bottom-up so indexes stay valid.
  const insertions = new Map<string, Map<number, string[]>>();
  for (const entry of classParameters) {
    const heading = findClassHeading(entry.className, headingsByPage, linesByPage, owners);
    if (!heading) {
      undocumented.push(entry.className);
      continue;
    }
    const headings = headingsByPage.get(heading.page) ?? [];
    const next = headings.find(
      candidate => candidate.line > heading.line && candidate.level <= heading.level
    );
    const lines = linesByPage.get(heading.page) ?? [];
    let end = next ? next.line : lines.length;
    while (end > heading.line + 1 && lines[end - 1].trim() === '') {
      end--;
    }
    const pageInsertions = insertions.get(heading.page) ?? new Map<number, string[]>();
    const block = [
      '',
      getBeginMarker(entry.className),
      '',
      renderClassParameters(entry, Math.min(heading.level + 1, 6)),
      '',
      END_MARKER
    ].join('\n');
    pageInsertions.set(end, [...(pageInsertions.get(end) ?? []), block]);
    insertions.set(heading.page, pageInsertions);
  }

  const pages = new Map<string, string>();
  for (const [page, originalLines] of linesByPage) {
    const lines = [...originalLines];
    for (const [index, blocks] of [...(insertions.get(page) ?? [])].sort(([a], [b]) => b - a)) {
      lines.splice(index, 0, ...blocks.join('\n').split('\n'));
    }
    pages.set(page, lines.join('\n'));
  }
  return {pages, undocumented};
}

function getBeginMarker(className: string): string {
  return `{/* parameters: ${className} ${MARKER_NOTE} */}`;
}

/** Removes old blocks before ownership discovery, so generated text cannot select its own owner. */
function removeParameterBlocks(lines: string[]): string[] {
  const output: string[] = [];
  for (let index = 0; index < lines.length; index++) {
    const match = BEGIN_MARKER.exec(lines[index]);
    if (!match) {
      output.push(lines[index]);
      continue;
    }
    let end = index + 1;
    while (end < lines.length && lines[end] !== END_MARKER) {
      end++;
    }
    if (end === lines.length) {
      throw new Error(`unterminated parameters block for ${match[1]}`);
    }
    if (output.at(-1) === '') {
      output.pop();
    }
    index = end;
  }
  return output.join('\n').split('\n');
}
