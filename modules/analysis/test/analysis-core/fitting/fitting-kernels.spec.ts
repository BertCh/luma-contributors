// Independent binary64 NumPy/SciPy fixtures, generated by generate-fitting-fixtures.py.
// Float32 Adam accumulates rounding in moments/powers; absolute tolerance 2e-5 for these short fits.
function expectClose(
  actual: readonly number[],
  expected: readonly number[],
  tolerance: number,
  label = 'value'
): void {
  expect(actual).toHaveLength(expected.length);
  for (const [index, value] of actual.entries()) {
    expect(Number.isFinite(value), `finite ${label} at ${index}`).toBe(true);
    expect(Math.abs(value - expected[index]), `${label} at ${index}`).toBeLessThanOrEqual(
      tolerance
    );
  }
}

it('reduces odd tiles, masked NaNs and padding rows against NumPy, bit-repeatably', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  for (const rowCount of [0, 1, 255, 256, 257, fixture.gradients.rowCount]) {
    const test = createFittingTestGraph(device);
    try {
      const gradients = Array.from({length: rowCount}, (_, row) => [
        ((row % 17) - 8) / 8,
        ((row % 11) - 5) / 4,
        1
      ]).flat();
      const mask = Array.from({length: rowCount}, (_, row) => (row % 13 ? 1 : 0));
      for (let row = 0; row < rowCount; row += 13) gradients[row * 3] = Number.NaN;
      const input = test.floats('gradients', gradients, 1);
      const maskView = test.uints('mask', mask, 1);
      const first = test.floats('first', [99, 99, 99], 1);
      const second = test.floats('second', [99, 99, 99], 1);
      for (const [id, sums] of [
        ['first', first],
        ['second', second]
      ] as const) {
        test.graph.add(
          new GPUFittingGradientSums({
            id,
            rowCount,
            parameterCount: 3,
            gradients: input,
            mask: maskView,
            output: {sums}
          })
        );
      }
      test.run();
      const actual = await test.readFloats(first);
      const expected = [0, 0, 0];
      for (let row = 0; row < rowCount; row++)
        if (mask[row]) {
          for (let parameter = 0; parameter < 3; parameter++)
            expected[parameter] += gradients[row * 3 + parameter];
        }
      expectClose(
        actual,
        rowCount === fixture.gradients.rowCount ? fixture.gradients.sums : expected,
        0
      );
      expect(await test.readFloats(second)).toEqual(actual);
      expect(await test.readFloatStorage(first)).toEqual([12345, ...actual, 12345]);
    } finally {
      test.destroy();
    }
  }
});

for (const model of ['quadratic', 'logistic'] as const) {
  it(`Adam on a ${model} matches NumPy weights, moments, every loss and budget status`, async () => {
    const device = await getWebGPUTestDevice();
    requireTestDevice(device);
    const test = createFittingTestGraph(device);
    const problem = fixture[model];
    try {
      const parameters = test.floats(
        'parameters',
        getGPUAdamStepParameterValues({learningRate: 0.05})
      );
      const gradients = test.floats('gradients', [0, 0, 0]);
      const loss = test.floats('loss', [0]);
      const output = {
        weights: test.floats('weights', problem.initial),
        firstMoment: test.floats('firstMoment', [0, 0, 0]),
        secondMoment: test.floats('secondMoment', [0, 0, 0]),
        lossHistory: test.floats('history', new Float32Array(problem.steps + 1).fill(-99)),
        status: {
          iterationCount: test.uints('iterations', [0]),
          converged: test.uints('converged', [0]),
          iterationLimitReached: test.uints('limited', [0]),
          invalidCount: test.uints('invalid', [0])
        }
      };
      const featureValues = model === 'logistic' ? fixture.logistic.features.flat() : [];
      const features = test.floats('features', featureValues);
      const labels = test.floats('labels', model === 'logistic' ? fixture.logistic.labels : []);
      const rowTerms = test.floats(
        'row-terms',
        new Float32Array(model === 'logistic' ? fixture.logistic.labels.length * 4 : 4)
      );
      const totals = test.floats('totals', [0, 0, 0, 0]);
      // One extra evaluation publishes the final iterate's loss; a further call checks frozen state.
      for (let iteration = 0; iteration <= problem.steps + 1; iteration++) {
        const prefix = `fit-${iteration}`;
        if (model === 'quadratic') {
          test.graph.add(
            createWGSLKernelNode(test.graph, {
              id: `${prefix}-evaluate`,
              operation: 'FittingTest',
              invocationCount: 1,
              bindings: [
                {name: 'weights', view: output.weights, type: 'f32', access: 'read'},
                {name: 'gradients', view: gradients, type: 'f32', access: 'read_write'},
                {name: 'loss', view: loss, type: 'f32', access: 'read_write'}
              ],
              body: `let optimum = array<f32, 3>(-1.0, 2.0, 0.0);
  var total = 0.0;
  for (var parameter = 0u; parameter < 3u; parameter++) {
    let residual = weights[weightsOffset + parameter] - optimum[parameter];
    let scale = f32(parameter + 1u);
    gradients[gradientsOffset + parameter] = scale * residual;
    total += 0.5 * scale * residual * residual;
  }
  loss[lossOffset] = total;`
            })
          );
        } else {
          test.graph.add(
            createWGSLKernelNode(test.graph, {
              id: `${prefix}-evaluate`,
              operation: 'FittingTest',
              invocationCount: fixture.logistic.labels.length,
              bindings: [
                {name: 'weights', view: output.weights, type: 'f32', access: 'read'},
                {name: 'features', view: features, type: 'f32', access: 'read'},
                {name: 'labels', view: labels, type: 'f32', access: 'read'},
                {name: 'terms', view: rowTerms, type: 'f32', access: 'read_write'}
              ],
              body: `var score = 0.0;
  for (var parameter = 0u; parameter < 3u; parameter++) {
    score += features[featuresOffset + index * 3u + parameter] * weights[weightsOffset + parameter];
  }
  let label = labels[labelsOffset + index];
  let residual = 1.0 / (1.0 + exp(-score)) - label;
  for (var parameter = 0u; parameter < 3u; parameter++) {
    terms[termsOffset + index * 4u + parameter] = residual * features[featuresOffset + index * 3u + parameter] / 9.0;
  }
  terms[termsOffset + index * 4u + 3u] = (max(score, 0.0) + log(1.0 + exp(-abs(score))) - label * score) / 9.0;`
            })
          );
          test.graph.add(
            new GPUFittingGradientSums({
              id: `${prefix}-sum`,
              rowCount: 9,
              parameterCount: 4,
              gradients: rowTerms,
              output: {sums: totals}
            })
          );
          test.graph.add(
            createWGSLKernelNode(test.graph, {
              id: `${prefix}-unpack`,
              operation: 'FittingTest',
              invocationCount: 1,
              bindings: [
                {name: 'totals', view: totals, type: 'f32', access: 'read'},
                {name: 'gradients', view: gradients, type: 'f32', access: 'read_write'},
                {name: 'loss', view: loss, type: 'f32', access: 'read_write'}
              ],
              body: `for (var parameter = 0u; parameter < 3u; parameter++) { gradients[gradientsOffset + parameter] = totals[totalsOffset + parameter]; }
  loss[lossOffset] = totals[totalsOffset + 3u];`
            })
          );
        }
        test.graph.add(
          new GPUAdamStep({
            id: `${prefix}-adam`,
            parameters,
            gradients,
            loss,
            maximumIterations: problem.steps,
            output
          })
        );
      }
      test.run();
      expectClose(await test.readFloats(output.weights), problem.weights, 2e-5, 'weights');
      expectClose(
        await test.readFloats(output.firstMoment),
        problem.firstMoment,
        2e-5,
        'firstMoment'
      );
      expectClose(
        await test.readFloats(output.secondMoment),
        problem.secondMoment,
        2e-5,
        'secondMoment'
      );
      expectClose(
        await test.readFloats(output.lossHistory),
        problem.lossHistory,
        2e-5,
        'lossHistory'
      );
      expect(await test.readUints(output.status.iterationCount)).toEqual([problem.steps]);
      expect(await test.readUints(output.status.converged)).toEqual([0]);
      expect(await test.readUints(output.status.iterationLimitReached)).toEqual([1]);
      expect(await test.readUints(output.status.invalidCount)).toEqual([0]);
    } finally {
      test.destroy();
    }
  });
}

it('Adam stops on a plateau, skips zero-gradient sparse slots and rejects invalid packed values', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  for (const mode of ['plateau', 'skip', 'zero-beta', 'invalid'] as const) {
    const test = createFittingTestGraph(device);
    try {
      const values = getGPUAdamStepParameterValues({
        learningRate: 0.05,
        tolerance: mode === 'plateau' ? 1e-4 : 0,
        skipZeroGradient: mode === 'skip',
        beta1: mode === 'zero-beta' ? 0 : 0.9,
        beta2: mode === 'zero-beta' ? 0 : 0.999
      });
      if (mode === 'invalid') values[2] = 1;
      const parameters = test.floats('parameters', values);
      const loss = test.floats('loss', [1]);
      const gradients = test.floats('gradients', mode === 'zero-beta' ? [2, -2] : [0, 0]);
      const output = {
        weights: test.floats('weights', [3, -2]),
        firstMoment: test.floats('first', [0.5, -0.25]),
        secondMoment: test.floats('second', [1, 2]),
        lossHistory: test.floats('history', [-99, -99, -99, -99]),
        status: {
          iterationCount: test.uints('iterations', [0]),
          converged: test.uints('converged', [0]),
          iterationLimitReached: test.uints('limited', [0]),
          invalidCount: test.uints('invalid', [0])
        }
      };
      const calls = mode === 'plateau' ? 4 : 1;
      for (let index = 0; index < calls; index++)
        test.graph.add(
          new GPUAdamStep({
            id: `step-${index}`,
            parameters,
            loss,
            gradients,
            maximumIterations: 3,
            output
          })
        );
      test.run();
      const actual = await test.readFloats(output.weights);
      if (mode === 'skip' || mode === 'invalid') expect(actual).toEqual([3, -2]);
      if (mode === 'skip') {
        expect(await test.readFloats(output.firstMoment)).toEqual([0.5, -0.25]);
        expect(await test.readFloats(output.secondMoment)).toEqual([1, 2]);
      }
      if (mode === 'zero-beta') expectClose(actual, [2.95, -1.95], 1e-6);
      expect(await test.readUints(output.status.iterationCount)).toEqual([
        mode === 'invalid' ? 0 : 1
      ]);
      expect(await test.readUints(output.status.converged)).toEqual([mode === 'plateau' ? 1 : 0]);
      expect(await test.readUints(output.status.invalidCount)).toEqual([
        mode === 'invalid' ? 1 : 0
      ]);
      expect(await test.readUints(output.status.iterationLimitReached)).toEqual([0]);
      if (mode === 'plateau')
        expect(await test.readFloats(output.lossHistory)).toEqual([1, 1, -99, -99]);
    } finally {
      test.destroy();
    }
  }
});

