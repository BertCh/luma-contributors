it('Adam updates a large finite gradient without overflowing its corrected denominator', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  const test = createFittingTestGraph(device);
  try {
    const gradient = Math.fround(1e20);
    const parameterValues = getGPUAdamStepParameterValues({learningRate: 0.05});
    const output = {
      weights: test.floats('weights', [0]),
      firstMoment: test.floats('first', [0]),
      secondMoment: test.floats('second', [0]),
      lossHistory: test.floats('history', [-99, -99]),
      status: {
        iterationCount: test.uints('iterations', [0]),
        converged: test.uints('converged', [0]),
        iterationLimitReached: test.uints('limited', [0]),
        invalidCount: test.uints('invalid', [0])
      }
    };
    test.graph.add(
      new GPUAdamStep({
        maximumIterations: 1,
        output,
        gradients: test.floats('gradient', [gradient]),
        loss: test.floats('loss', [1]),
        parameters: test.floats('parameters', parameterValues)
      })
    );
    test.run();
    // Independent first-step closed form: corrected moments are g and g^2, so the update is
    // -learningRate * g / (abs(g) + epsilon). The stored second moment is finite even though
    // g^2 itself is outside float32 range. Compute expected moments in binary64, rounding once.
    const expectedFirst = Math.fround((1 - parameterValues[1]) * gradient);
    const expectedSecond = Math.fround((1 - parameterValues[2]) * gradient * gradient);
    const expectedWeight =
      (-parameterValues[0] * gradient) / (Math.abs(gradient) + parameterValues[3]);
    const actualWeights = await test.readFloats(output.weights);
    const actualFirst = await test.readFloats(output.firstMoment);
    const actualSecond = await test.readFloats(output.secondMoment);
    const report = `weight=${actualWeights[0]}, first=${actualFirst[0]}, second=${actualSecond[0]}`;
    expectClose(actualFirst, [expectedFirst], 2e-6 * expectedFirst, `first moment (${report})`);
    expectClose(actualSecond, [expectedSecond], 2e-6 * expectedSecond, `second moment (${report})`);
    expectClose(actualWeights, [expectedWeight], 1e-6, `weight (${report})`);
    expect(await test.readFloats(output.lossHistory)).toEqual([1, -99]);
    expect(await test.readUints(output.status.iterationCount)).toEqual([1]);
    expect(await test.readUints(output.status.converged)).toEqual([0]);
    expect(await test.readUints(output.status.iterationLimitReached)).toEqual([1]);
    expect(await test.readUints(output.status.invalidCount)).toEqual([0]);
  } finally {
    test.destroy();
  }
});

it('keeps Adam moment contributions and corrected roots within range at exponent boundaries', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  const test = createFittingTestGraph(device);
  try {
    const contributionCases = [
      {gradient: 0, beta: 0.999},
      {gradient: 1, beta: 0.999},
      {gradient: -1, beta: 0.999},
      {gradient: 2 ** 63, beta: 0.999},
      {gradient: 2 ** 63 * (1 + 2 ** -23), beta: 0.999},
      {gradient: 2 ** 64, beta: 0.5},
      {gradient: -(2 ** 64), beta: 0.5},
      {gradient: 1e20, beta: 0.999},
      {gradient: -1e20, beta: 0.999},
      {gradient: 1e21, beta: 0.9999},
      {gradient: 1e22, beta: 1 - 2 ** -24}
    ].map(problem => ({gradient: Math.fround(problem.gradient), beta: Math.fround(problem.beta)}));
    const rootCases = [
      {second: 0, correction: 1},
      {second: 1, correction: 1},
      {second: 2, correction: 1},
      {second: 3, correction: 0.5},
      {second: 1e37, correction: 0.001},
      {second: 3e38, correction: 2 ** -24},
      {second: 2 ** -126, correction: 1},
      {second: 2 ** -125, correction: 1}
    ].map(problem => ({
      second: Math.fround(problem.second),
      correction: Math.fround(problem.correction)
    }));
    const contributions = test.floats('contributions', new Float32Array(contributionCases.length));
    const roots = test.floats('roots', new Float32Array(rootCases.length));
    const contributionInputs = test.floats(
      'contribution-inputs',
      contributionCases.flatMap(problem => [problem.gradient, problem.beta])
    );
    const rootInputs = test.floats(
      'root-inputs',
      rootCases.flatMap(problem => [problem.second, problem.correction])
    );
    for (const [name, inputs, output, body] of [
      [
        'contribution',
        contributionInputs,
        contributions,
        'getAdamSecondMomentContribution(inputs[inputsOffset + 2u * index], inputs[inputsOffset + 2u * index + 1u])'
      ],
      [
        'root',
        rootInputs,
        roots,
        'getAdamCorrectedSecondMomentRoot(inputs[inputsOffset + 2u * index], inputs[inputsOffset + 2u * index + 1u])'
      ]
    ] as const) {
      test.graph.add(
        createWGSLKernelNode(test.graph, {
          id: name,
          operation: 'FittingTest',
          invocationCount: output.length,
          bindings: [
            {name: 'inputs', view: inputs, type: 'f32', access: 'read'},
            {name: 'result', view: output, type: 'f32', access: 'read_write'}
          ],
          declarations: ADAM_MOMENT_RANGE_WGSL,
          body: `result[resultOffset + index] = ${body};`
        })
      );
    }
    test.run();
    const actualContributions = await test.readFloats(contributions);
    for (const [index, problem] of contributionCases.entries()) {
      // Binary64 squares/products are representable here, independently of the shader's
      // exponent decomposition. Round only the final stored moment to float32.
      const expected = Math.fround((1 - problem.beta) * problem.gradient * problem.gradient);
      expectClose(
        [actualContributions[index]],
        [expected],
        Math.abs(expected) * 2e-6,
        `contribution for gradient=${problem.gradient}, beta=${problem.beta}`
      );
    }
    const actualRoots = await test.readFloats(roots);
    for (const [index, problem] of rootCases.entries()) {
      const expected = Math.sqrt(problem.second / problem.correction);
      expectClose(
        [actualRoots[index]],
        [expected],
        expected * 2e-6,
        `root for second=${problem.second}, correction=${problem.correction}`
      );
    }
  } finally {
    test.destroy();
  }
});

