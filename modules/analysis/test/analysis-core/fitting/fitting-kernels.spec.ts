it('restores Adam update scales with float32 rounding at normal and subnormal boundaries', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  const test = createFittingTestGraph(device);
  try {
    const cases = [
      {significand: 1, exponent: 0},
      {significand: 1.5, exponent: 127},
      {significand: 1, exponent: -126},
      {significand: 2, exponent: -127},
      {significand: 1, exponent: -149},
      {significand: 1, exponent: -150},
      {significand: 1.5, exponent: -150},
      {significand: 1.5, exponent: -151},
      {significand: 1.5, exponent: -149},
      {significand: 1.25, exponent: -148},
      {significand: 1, exponent: 128}
    ];
    const significands = test.floats(
      'significands',
      cases.map(problem => problem.significand)
    );
    const exponents = test.uints(
      'exponents',
      Uint32Array.from(cases.map(problem => problem.exponent))
    );
    const result = test.uints('result', new Uint32Array(cases.length));
    test.graph.add(
      createWGSLKernelNode(test.graph, {
        id: 'scale-restoration',
        operation: 'FittingTest',
        invocationCount: cases.length,
        bindings: [
          {name: 'significands', view: significands, type: 'f32', access: 'read'},
          {name: 'exponents', view: exponents, type: 'u32', access: 'read'},
          {name: 'result', view: result, type: 'u32', access: 'read_write'}
        ],
        declarations: ADAM_MOMENT_RANGE_WGSL,
        body: `let value = getAdamScaledMagnitude(significands[significandsOffset + index], bitcast<i32>(exponents[exponentsOffset + index]));
  result[resultOffset + index] = bitcast<u32>(value);`
      })
    );
    test.run();
    const expectedBits = cases.map(
      problem =>
        new Uint32Array(Float32Array.of(problem.significand * 2 ** problem.exponent).buffer)[0]
    );
    expect(await test.readUints(result)).toEqual(expectedBits);
  } finally {
    test.destroy();
  }
});
