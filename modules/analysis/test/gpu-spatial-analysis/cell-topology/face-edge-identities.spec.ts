import {getWebGPUTestDevice} from '@luma.gl/core/test-utils';
import {expect, it} from 'vitest';
import {GPUContributorOperation} from '../../../src/analysis-core/operations/gpu-contributor-operation';
import {GPUCellTopology} from '../../../src/gpu-spatial-analysis/cell-topology/gpu-cell-topology';
import {GPUH3CellIdentities} from '../../../src/gpu-spatial-analysis/cell-topology/gpu-h3-cell-identities';
import {requireTestDevice} from '../../../src/testing/require-test-device';
import {runOperationGraph} from '../../utils/mixed-execution-test-utils';
import fixture from './face-edge-identities-fixture.json';
import {joinIdentityWords} from './identity-key-readback';

// Independent literals generated by s2-geometry 1.2.10 FromFaceIJ/getNeighbors/toId
// at all six cube faces' edges and corners (levels 10, 20, 26), and by h3-js
// getPentagons/originToDirectedEdges/cellToVertexes (resolutions 0, 1, 5, 10, 15),
// plus Class III cells whose getIcosahedronFaces spans faces. No GPU/CPU twin supplies truth.
function splitKey(key: bigint): number[] {
  return [Number(key & 0xffffffffn), Number(key >> 32n)];
}

it('S2 high-level cube face-edge and corner neighbors match s2-geometry (DGGS-114)', async () => {
  const device = await getWebGPUTestDevice();
  requireTestDevice(device);
  const result = await runOperationGraph(device, {
    inputs: {
      cells: {
        format: 'uint32x2',
        values: Uint32Array.from(fixture.s2.flatMap(row => splitKey(BigInt(row.key))))
      }
    },
    operations: [
      new GPUContributorOperation({
        id: 's2-face-edges',
        inputs: {cells: 'cells'},
        outputs: {
          neighbors: {value: 'neighbors', format: 'uint32x2', length: fixture.s2.length * 4},
          counts: {value: 'counts', format: 'uint32', length: fixture.s2.length}
        },
        createContributor: getView =>
          new GPUCellTopology({
            family: 's2',
            operation: {type: 'ring', k: 1},
            cells: getView<'uint32x2'>('cells'),
            output: {cells: getView<'uint32x2'>('neighbors'), counts: getView<'uint32'>('counts')}
          })
      })
    ],
    outputs: ['neighbors', 'counts']
  });
  expect(result['neighbors']).toHaveLength(fixture.s2.length * 8);
  expect(result['counts']).toHaveLength(fixture.s2.length);
  const actual = joinIdentityWords(result['neighbors'], fixture.s2.length * 4);
  fixture.s2.forEach((row, index) => {
    expect(result['counts'][index], row.key).toBe(4);
    expect(actual.slice(index * 4, index * 4 + 4), row.key).toEqual(row.neighbors.map(BigInt));
  });
});

for (const operation of ['directed-edges', 'vertices'] as const) {
  it(`H3 ${operation} preserve pentagon deleted directions and face-crossing identities (DGGS-114)`, async () => {
    const device = await getWebGPUTestDevice();
    requireTestDevice(device);
    const result = await runOperationGraph(device, {
      inputs: {
        cells: {
          format: 'uint32x2',
          values: Uint32Array.from(fixture.h3.flatMap(row => splitKey(BigInt(`0x${row.cell}`))))
        }
      },
      operations: [
        new GPUContributorOperation({
          id: `h3-face-${operation}`,
          inputs: {cells: 'cells'},
          outputs: {
            identities: {value: 'identities', format: 'uint32x2', length: fixture.h3.length * 6}
          },
          createContributor: getView =>
            new GPUH3CellIdentities({
              operation,
              cells: getView<'uint32x2'>('cells'),
              output: getView<'uint32x2'>('identities')
            })
        })
      ],
      outputs: ['identities']
    });
    expect(result['identities']).toHaveLength(fixture.h3.length * 12);
    const actual = joinIdentityWords(result['identities'], fixture.h3.length * 6);
    fixture.h3.forEach((row, index) => {
      const expected = operation === 'vertices' ? row.vertices : row.edges;
      expect(actual.slice(index * 6, index * 6 + 6), row.cell).toEqual(
        expected.map(key => BigInt(`0x${key}`))
      );
    });
  });
}
