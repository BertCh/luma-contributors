export function expectOracleRows(
  actual: Record<string, ArrayLike<number>>,
  expected: Record<string, readonly number[]>
) {
  for (const [name, values] of Object.entries(expected)) {
    expect(actual[name].length, name).toBe(values.length);
    for (let index = 0; index < values.length; index++) {
      // Use the independent expected links, never the actual links, to select coordinates.
      // A broken link cannot hide an unwritten active coordinate or a wrong sentinel tail:
      // every link is still compared below, and all expected active coordinates reject NaN.
      if (
        name === 'offsetPositions' &&
        expected['offsetLinks']?.[index - (index % 2)] === 0xffffffff
      )
        continue;
      expect(Number.isFinite(actual[name][index]), `${name}[${index}]`).toBe(true);
      // Integer IDs/offsets/masks and copied coordinates compare exactly; computed coordinates
      // allow 3e-5 planar units (a few f32 roundings on this small, well-conditioned fixture).
      if (['segments', 'offsetPositions', 'positions', 'circles'].includes(name))
        expect(
          Math.abs(actual[name][index] - values[index]),
          `${name}[${index}]`
        ).toBeLessThanOrEqual(3e-5);
      else expect(actual[name][index], `${name}[${index}]`).toBe(values[index]);
    }
  }
}
