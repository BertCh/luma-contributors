/** Literals below come from supporting-line intersections, not either skeleton implementation. */
export function getConvexOracleCase() {
  // At time t the rectangle is [t,4-t] x [t,2-t]. Opposite horizontal supports meet at t=1.
  // Each corner bisector ends at (1,1) or (3,1); the remaining horizontal ridge joins those points.
  // A corner is generated by its incoming and outgoing edge rows; the terminal ridge has no pair.
  const props = {
    positions: 'positions',
    ringOffsets: 'ringOffsets',
    polygonCount: 1,
    maximumVertices: 4,
    maximumIterations: 8,
    segmentCapacity: 5,
    offsetDistance: 0.5,
    output: skeletonOutput
  };
  return {
    name: 'convex rectangle supporting lines',
    inputs: rectangleInputs(),
    gpu: () => new GPUConvexStraightSkeletonOperation(props),
    cpu: () => new CPUConvexStraightSkeletonOperation(props),
    expected: {
      segments: [0, 0, 1, 1, 4, 0, 3, 1, 4, 2, 3, 1, 0, 2, 1, 1, 1, 1, 3, 1],
      sourceEdges: [3, 0, 0, 1, 1, 2, 2, 3, 0xffffffff, 0xffffffff],
      offsetPositions: [0.5, 0.5, 3.5, 0.5, 3.5, 1.5, 0.5, 1.5],
      status: [5, 5, 4, 0]
    }
  };
}

export function getVectorOracleCase() {
  // Same geometric derivation as convex. Event order is the right collapse, then the left.
  // Slots 0..3 retain the original circular adjacency at the t=1/2 snapshot; no birth is needed.
  const props = {
    ...geometryNames,
    polygonCount: 1,
    maximumVertices: 4,
    maximumEvents: 8,
    segmentCapacity: 5,
    offsetDistance: 0.5,
    output: {...skeletonOutput, offsetLinks: 'offsetLinks'}
  };
  return {
    name: 'vector rectangle supporting lines and links',
    inputs: {
      ...rectangleInputs(),
      polygonOffsets: offsets([0, 1]),
      featureOffsets: offsets([0, 1])
    },
    gpu: () => new GPUVectorStraightSkeletonOperation(props),
    cpu: () => new CPUVectorStraightSkeletonOperation(props),
    expected: {
      segments: [4, 0, 3, 1, 4, 2, 3, 1, 0, 0, 1, 1, 0, 2, 1, 1, 1, 1, 3, 1],
      sourceEdges: [0, 1, 1, 2, 3, 0, 2, 3, 0, 2],
      // Inactive-coordinate placeholders retain the block shape, but only links define
      // usability. GPU snapshots leave those coordinate words untouched; the CPU zeroes them.
      offsetPositions: [0.5, 0.5, 3.5, 0.5, 3.5, 1.5, 0.5, 1.5, ...Array(32).fill(0)],
      offsetLinks: [3, 1, 0, 2, 1, 3, 2, 0, ...Array(32).fill(0xffffffff)],
      status: [5, 5, 4, 0]
    }
  };
}

export function getLoopOracleCase() {
  // y=x intersects y=1-2x at (1/3,1/3). Chronological erasure removes the closed excursion
  // through (1,1),(0,1); the retained outgoing edges start at original rows 0 and 2.
  const props = {
    lines: {positions: 'inputPositions', lineOffsets: 'inputOffsets'},
    lineCount: 1,
    vertexCapacity: 3,
    intersectionCapacity: 8,
    output: {
      positions: 'positions',
      lineOffsets: 'lineOffsets',
      sourceEdges: 'sourceEdges',
      status: 'status'
    }
  };
  return {
    name: 'loop rational crossing and original edge rows',
    inputs: {inputPositions: positions([0, 0, 1, 1, 0, 1, 1, -1]), inputOffsets: offsets([0, 4])},
    gpu: () => new GPULineLoopRemovalOperation(props),
    cpu: () => new CPULineLoopRemovalOperation(props),
    expected: {
      positions: [0, 0, 1 / 3, 1 / 3, 1, -1],
      lineOffsets: [0, 3],
      sourceEdges: [0, 2, 2],
      status: [3, 3, 0, 0]
    }
  };
}

export function getCircleOracleCase() {
  // A 4x4 square's unique optimum is its center (12,22), radius 2. The nearest boundary
  // tie goes to the first visited edge, closing (10,24)->(10,20), so witness=(10,22).
  // CPU attains the envelope cap 2, proving zero error. GPU root Lipschitz gap is 2*sqrt(2).
  const props = {
    ...geometryNames,
    featureCount: 1,
    tolerance: 3,
    cellCapacity: 4,
    maximumIterations: 8,
    output: {circles: 'circles', witnesses: 'witnesses', status: 'status'}
  };
  return {
    name: 'circle square boundary witness',
    inputs: {
      positions: positions([10, 20, 14, 20, 14, 24, 10, 24]),
      ringOffsets: offsets([0, 4]),
      polygonOffsets: offsets([0, 1]),
      featureOffsets: offsets([0, 1])
    },
    gpu: () => new GPUMaximumInscribedCircleOperation(props),
    cpu: () => new CPUMaximumInscribedCircleOperation(props),
    expected: {circles: [12, 22, 2, 0], witnesses: [10, 22], status: [0]},
    gpuExpected: {circles: [12, 22, 2, 2 * Math.SQRT2], witnesses: [10, 22], status: [0]}
  };
}

export function getTreeOracleCase() {
  // Two leaf points under a collection: descending canonical order places (4,3) before (1,2).
  // IDs 91 and 17 do not determine geometry order. Nodes remain in original postorder rows.
  const props = {
    positions: 'positions',
    nodes: 'nodes',
    children: 'children',
    rowCount: 2,
    nodeCount: 3,
    childCount: 2,
    output: {positions: 'positionsOutput', children: 'childrenOutput', status: 'status'}
  };
  return {
    name: 'tree descending child order',
    inputs: {
      positions: positions([1, 2, 4, 3]),
      nodes: {
        format: 'uint32x4' as const,
        values: Uint32Array.of(0, 0, 1, 91, 0, 1, 1, 17, 7, 0, 2, 55)
      },
      children: offsets([0, 1])
    },
    gpu: () => new GPUNormalizeGeometryOperation(props),
    cpu: () => new CPUNormalizeGeometryOperation(props),
    expected: {positionsOutput: [1, 2, 4, 3], childrenOutput: [1, 0], status: [0, 0, 0]}
  };
}

