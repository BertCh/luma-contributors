it('Brier probabilities saturate correctly when the standardized threshold exceeds float32 range', () => {
  const fixture = GAUSSIAN_BRIER_TAIL_EXPECTED;
  const actual = computeGaussianPredictiveScoresOnCPU(
    {
      means: Float32Array.from(fixture.means),
      variances: Float32Array.from(fixture.variances),
      observations: Float32Array.from(fixture.observations)
    },
    {scores: ['brierScore'], brierThreshold: 0}
  );
  expectRows(actual.brierScore!, fixture.expected);
});

function expectRows(actual: ArrayLike<number>, expected: readonly (number | null)[]) {
  expect(actual.length).toBe(expected.length);
  let maximum = 0;
  expected.forEach((value, row) => {
    if (value === null) expect(actual[row]).toBeNaN();
    else {
      expect(Number.isFinite(actual[row])).toBe(true);
      maximum = Math.max(maximum, Math.abs(actual[row] - value));
      expect(Math.abs(actual[row] - value)).toBeLessThanOrEqual(
        2e-6 * Math.max(1, Math.abs(value))
      );
    }
  });
  return maximum;
}

it('all Gaussian CPU score outputs match independent SciPy literals', () => {
  const differences = {crps: 0, logScore: 0, brierScore: 0, intervalScore: 0};
  for (const scaled of [false, true]) {
    const input = createGaussianProperScoresInput(scaled);
    const expected = scaled
      ? GAUSSIAN_PROPER_SCORES_EXPECTED.scaled
      : GAUSSIAN_PROPER_SCORES_EXPECTED.base;
    const actual = computeGaussianPredictiveScoresOnCPU(input, {
      scores: OPTIONAL_SCORES,
      brierThreshold: scaled ? 18 : 1,
      intervalAlpha: 0.1
    });
    for (const name of SCORES) {
      differences[name] = Math.max(differences[name], expectRows(actual[name]!, expected[name]));
    }
  }
  console.info('Gaussian proper-score CPU maximum absolute differences', differences);
});

it('Gaussian quantiles and error-function helpers match independent SciPy across all branches', () => {
  for (const [alpha, expected] of GAUSSIAN_PROPER_SCORES_EXPECTED.quantiles) {
    expect(Number.isFinite(getGaussianIntervalMultiplier(alpha))).toBe(true);
    expect(Math.abs(getGaussianIntervalMultiplier(alpha) - expected)).toBeLessThan(3e-14);
  }
  for (const [argument, expected] of GAUSSIAN_PROPER_SCORES_EXPECTED.erf) {
    expect(Math.abs(getGaussianScoreErrorFunction(argument) - expected)).toBeLessThan(3e-15);
  }
});

it('Gaussian score forms reject missing thresholds, unrepresentable levels, invalid outputs and short rows', () => {
  const input = createGaussianProperScoresInput();
  expect(() => computeGaussianPredictiveScoresOnCPU(input, {scores: ['brierScore']})).toThrow(
    /brierThreshold/
  );
  for (const intervalAlpha of [0, 1, NaN, 1e-40, 0.999999999]) {
    expect(() =>
      computeGaussianPredictiveScoresOnCPU(input, {scores: ['intervalScore'], intervalAlpha})
    ).toThrow(/intervalAlpha/);
  }
  expect(() =>
    computeGaussianPredictiveScoresOnCPU({...input, observations: new Float32Array(11)})
  ).toThrow(/one row per mean/);
  expect(() => computeGaussianPredictiveScoresOnCPU(input, {brierThreshold: 1e40})).toThrow(
    /brierThreshold/
  );
  const graph = new GPUCommandGraph(createNullWebGPUDevice(), {id: 'gaussian-proper-validation'});
  const view = (name: string, length = 12) => createTransientView(graph, name, 'float32', length);
  const props = {
    means: view('means'),
    variances: view('variances'),
    observations: view('observations'),
    output: {crps: view('crps')}
  };
  expect(
    () =>
      new GPUGaussianPredictiveScores({
        ...props,
        output: {...props.output, brierScore: view('brier')}
      })
  ).toThrow(/brierThreshold/);
  expect(
    () =>
      new GPUGaussianPredictiveScores({
        ...props,
        output: {...props.output, logScore: view('short', 11)}
      })
  ).toThrow(/one row per mean/);
  expect(
    () =>
      new GPUGaussianPredictiveScores({
        ...props,
        output: {...props.output, logScore: props.output.crps}
      })
  ).toThrow();
  const nodes = new GPUGaussianPredictiveScores({
    ...props,
    brierThreshold: 1,
    intervalAlpha: 0.1,
    output: {
      ...props.output,
      logScore: view('log'),
      brierScore: view('brier-2'),
      intervalScore: view('interval')
    }
  }).getCommandNodes(graph);
  const sources = getParsedKernelSources(nodes);
  for (const {source} of sources.configurations) expect(getStorageBindingCount(source)).toBe(7);
});

