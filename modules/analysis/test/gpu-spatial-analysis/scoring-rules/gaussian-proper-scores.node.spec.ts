it('all Gaussian chunked score outputs fit eight bindings and validate the same chunk topology', () => {
  const graph = new GPUCommandGraph(createNullWebGPUDevice(), {id: 'gaussian-all-chunks'});
  const rows = (name: string, lengths = [3, 4, 5]) =>
    createVectorView(
      name,
      'float32',
      lengths.map((length, index) => {
        const backing = createTransientView(
          graph,
          `${name}-${index}`,
          'float32',
          length + index + 1
        );
        return graph.createDataView(backing.buffer, {
          format: 'float32',
          byteOffset: (index + 1) * 4,
          length
        });
      })
    );
  const props = {
    means: rows('means'),
    variances: rows('variances'),
    observations: rows('observations'),
    brierThreshold: 1,
    intervalAlpha: 0.1,
    output: {
      crps: rows('crps'),
      logScore: rows('log'),
      brierScore: rows('brier'),
      intervalScore: rows('interval')
    }
  };
  const contributor = new GPUGaussianPredictiveScores(props);
  for (const {source} of getParsedKernelSources(contributor.getCommandNodes(graph)).configurations)
    expect(getStorageBindingCount(source)).toBe(8);
  expect(
    () =>
      new GPUGaussianPredictiveScores({
        ...props,
        output: {...props.output, intervalScore: rows('bad-interval', [4, 3, 5])}
      })
  ).toThrow(/topology/);
});
