it('the GPU Brier tail tolerance covers float32 argument and exponent rounding', () => {
  // Independent SciPy erfc at f32(8 * f32(1/sqrt(2))), generated by the Python oracle.
  // At an exponent near -33, one f32 ULP is 2^-18. Squaring exp doubles
  // its relative effect; this probe does not evaluate the shader's erfc polynomial.
  const expected = 3.8700350466643384e-31;
  const roundedArgumentScore = 3.870043653092818e-31;
  const roundedScore = Math.fround(roundedArgumentScore * Math.exp(2 * 2 ** -18));
  expect(Number.isFinite(roundedScore)).toBe(true);
  expect(Math.abs(roundedScore / expected - 1)).toBeLessThanOrEqual(
    GAUSSIAN_BRIER_TAIL_RELATIVE_TOLERANCE
  );
  expect(Math.abs(0 / expected - 1)).toBeGreaterThan(GAUSSIAN_BRIER_TAIL_RELATIVE_TOLERANCE);
});

it('R7 Brier scores retain representable small normal tails', () => {
  // SciPy norm.sf(abs(z))**2; direct survival probability avoids subtraction from one.
  for (const [magnitude, expected] of [
    [6, 9.733551813410284e-19],
    [8, 3.8700350466643384e-31],
    [9, 1.2737117900534112e-38]
  ]) {
    for (const sign of [-1, 1]) {
      const actual = computeGaussianPredictiveScoresOnCPU(
        {
          means: Float32Array.of(sign * magnitude),
          observations: Float32Array.of(sign * magnitude),
          variances: Float32Array.of(1)
        },
        {scores: ['brierScore'], brierThreshold: 0}
      ).brierScore![0];
      expect(Number.isFinite(actual)).toBe(true);
      expect(Math.abs(actual / expected - 1)).toBeLessThan(2e-6);
    }
  }
});

