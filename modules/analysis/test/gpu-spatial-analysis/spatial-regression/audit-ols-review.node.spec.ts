it('R9 finite small Student t retains the complementary beta argument', () => {
  expect(getStudentTTwoSidedPValue(1e-6, 65534)).toBeCloseTo(0.9999992021184829, 14);
});

it('R9 finite huge Student t retains the representable Cauchy tail', () => {
  // df=1 is the Cauchy distribution: 2 atan(1/|t|)/pi avoids overflow and cancellation.
  const expected = (2 * Math.atan(1e-160)) / Math.PI;
  const actual = getStudentTTwoSidedPValue(1e160, 1);
  expect(Number.isFinite(actual)).toBe(true);
  expect(Math.abs(actual / expected - 1)).toBeLessThan(1e-12);
});

for (const scale of [1, 2 ** 32, 2 ** -40]) {
  it(`R8 standardized OLS diagnostics are invariant to response scale ${scale}`, () => {
    const device = createNullWebGPUDevice();
    try {
      const graph = new GPUCommandGraph(device);
      let serial = 0;
      const view = <Format extends 'float32' | 'uint32'>(format: Format, length: number) =>
        createTransientView(graph, `diagnostic-${serial++}`, format, length);
      const predictors = view('float32', 4);
      const response = view('float32', 4);
      const output = {
        coefficients: view('float32', 2),
        standardErrors: view('float32', 2),
        tStatistics: view('float32', 2),
        summary: view('float32', 22),
        status: {code: view('uint32', 1)}
      };
      const memory = createCPUGraphMemory();
      memory.write(predictors, Float32Array.of(-1, -1, 1, 1));
      memory.write(
        response,
        Float32Array.from([-1, 1, -2, 2], value => scale * value)
      );
      const nodes = new GPUOrdinaryLeastSquares({
        predictorCount: 1,
        predictors,
        response,
        output
      }).getCommandNodes(graph);
      // Only the main fit/report path is interpreted: dense Cholesky argument-array assignment
      // is unsupported by wgsl_reflect on the auxiliary fit. The native test asserts KB/BP too.
      executeCommandNodesOnCPU(
        nodes.filter(node => !node.id.includes('-bp-')),
        memory
      );
      const summary = memory.readFloat32(output.summary);
      // Independently computed by SciPy in audit-ols-review.oracle.py: scaling cancels.
      for (const [slot, expected] of [
        [14, 1.36],
        [7, 0.4482666666666666]
      ]) {
        expect(Number.isFinite(summary[slot]), `summary[${slot}]=${summary[slot]}`).toBe(true);
        expect(summary[slot]).toBeCloseTo(expected, 5);
      }
      const host = computeOrdinaryLeastSquaresOnCPU(
        {
          predictors: Float32Array.of(-1, -1, 1, 1),
          response: Float32Array.from([-1, 1, -2, 2], value => scale * value)
        },
        1
      );
      for (const [slot, expected] of [
        [14, 1.36],
        [7, 0.4482666666666666],
        [9, 4],
        [16, 0.72]
      ])
        expect(host.summary[slot]).toBeCloseTo(expected, 5);
    } finally {
      device.destroy();
    }
  });
}

