export async function checkTranslatedSingularity(
  harness: Harness,
  execute: ReviewExecution,
  translation: number,
  read: Harness['read']
) {
  const {port, graph} = harness;
  const output = {
    varianceInflationFactors: port('float32', Array(18).fill(-999)),
    conditionNumbers: port('float32', Array(9).fill(-999)),
    status: port('uint32', Array(9).fill(99))
  };
  const nodes = new GPULocalCollinearity({
    predictorCount: 2,
    predictors: port(
      'float32',
      Array.from({length: 9}, (_, row) => {
        const value = Number(row % 3 === 0);
        return [translation + value, value];
      }).flat()
    ),
    weights: {
      offsets: port(
        'uint32',
        Array.from({length: 10}, (_, row) => row * 9)
      ),
      neighbors: port(
        'uint32',
        Array.from({length: 81}, (_, slot) => slot % 9)
      ),
      weights: port('float32', Array(81).fill(1))
    },
    output
  }).getCommandNodes(graph);
  await execute(nodes);
  // Identical centered columns have rank one, independently of their translation.
  expect(await read(output.status)).toEqual(Array(9).fill(2));
  expect((await read(output.varianceInflationFactors)).every(Number.isNaN)).toBe(true);
  for (const value of await read(output.conditionNumbers)) {
    expect(Number.isFinite(value)).toBe(true);
    expect(Math.abs(value / 3e38 - 1)).toBeLessThan(1e-6);
  }
}

export async function checkCountCompleteness(
  harness: Harness,
  execute: ReviewExecution,
  chunked: boolean | 'chunk',
  read: Harness['read'],
  capacity = 32,
  includeCount = true
) {
  const {port, graph, set} = harness;
  const completeCount = chunked === 'chunk' ? 16 : 32;
  const requiredCount = port('uint32', [completeCount]);
  const count = port('uint32', [completeCount]);
  const status = {requiredCount, ...(includeCount ? {count} : {})};
  const createWeights = (rows: number, edgeCapacity: number) => ({
    offsets: port(
      'uint32',
      Array.from({length: rows + 1}, (_, row) => row * 4)
    ),
    neighbors: port(
      'uint32',
      Array.from({length: edgeCapacity}, (_, slot) => slot % 4)
    ),
    weights: port('float32', Array(edgeCapacity).fill(1))
  });
  const output = {
    varianceInflationFactors: port('float32', Array(8).fill(-999)),
    conditionNumbers: port('float32', Array(8).fill(-999)),
    designConditionNumbers: port('float32', Array(8).fill(-999)),
    varianceDecomposition: port('float32', Array(16).fill(-999)),
    status: port('uint32', Array(8).fill(99))
  };
  const weights = chunked
    ? {
        rowCount: 8,
        chunks: [
          {rowStart: 0, rowCount: 4, weights: createWeights(4, capacity / 2)},
          {
            rowStart: 4,
            rowCount: 4,
            weights: {...createWeights(4, capacity / 2), ...(chunked === 'chunk' ? {status} : {})}
          }
        ],
        ...(chunked === 'chunk' ? {} : {status})
      }
    : {...createWeights(8, capacity), status};
  const nodes = new GPULocalCollinearity({
    predictorCount: 1,
    predictors: port('float32', [0, 2, 0, 2, 0, 2, 0, 2]),
    weights,
    output
  }).getCommandNodes(graph);
  for (const required of [completeCount, completeCount + 1, completeCount]) {
    set(requiredCount, [required]);
    await execute(nodes);
    expect(await read(output.status)).toEqual(Array(8).fill(required === completeCount ? 0 : 1));
    for (const [name, view] of Object.entries(output)) {
      if (name === 'status') continue;
      const values = await read(view);
      if (required > completeCount) expect(values.every(Number.isNaN), name).toBe(true);
      else
        for (const value of values) {
          expect(Number.isFinite(value)).toBe(true);
          expect(
            Math.abs(
              value -
                (name === 'varianceDecomposition'
                  ? 0.8535533905932737
                  : name === 'designConditionNumbers'
                    ? 2.414213562373095
                    : 1)
            )
          ).toBeLessThan(1e-5);
        }
    }
  }
}

export function createReviewNonstationarity(harness: Harness, permutations: number) {
  const {port, graph} = harness;
  const parameters = port(
    'uint32',
    getGPUPermutationParameterValues({seed: 12345, permutationCount: permutations})
  );
  const output = {
    table: port('float32', Array(12).fill(-999)),
    summary: port('float32', Array(4).fill(-999)),
    standardDeviations: port('float32', Array((permutations + 1) * 2).fill(-999))
  };
  const contributor = new GPUGeographicallyWeightedRegressionNonstationarityTest({
    positions: port('float32x2', Array.from({length: 8}, (_, row) => [row, 0]).flat()),
    predictors: port('float32', [-1, 1, -1, 1, -1, 1, -1, 1]),
    predictorCount: 1,
    response: port('float32', [0, 2, 0, 2, 0, 2, 0, 2]),
    coefficients: port('float32', Array.from({length: 8}, () => [1, 1]).flat()),
    selectedBandwidth: port('float32', [0, 3]),
    bandwidthParameters: port('float32', [0, 0, 1, 0, 3]),
    parameters,
    maximumBandwidthCount: 1,
    maximumPermutations: permutations,
    indexGridSize: false,
    output
  });
  return {parameters, output, nodes: contributor.getCommandNodes(graph)};
}

export async function checkNonzeroTies(
  harness: Harness,
  execute: ReviewExecution,
  read: Harness['read']
) {
  const {port, graph} = harness;
  const {nodes, output} = createReviewNonstationarity(harness, 10);
  const finish = nodes.find(node => node.id.endsWith('-finish'))!;
  const bindings = harness.record(finish).bindings;
  const fitCounts = bindings.find(binding => binding.name === 'fitCounts')!.view;
  const rows = bindings.find(binding => binding.name === 'rows')!.view;
  const initial = port('float32', Array(22).fill(0.1));
  const prepare = createWGSLKernelNode(graph, {
    id: 'review-tie-prepare',
    operation: 'GWRReview',
    invocationCount: 22,
    bindings: [
      {name: 'initial', view: initial, type: 'f32', access: 'read'},
      {name: 'distribution', view: output.standardDeviations, type: 'f32', access: 'read_write'},
      {name: 'counts', view: fitCounts, type: 'f32', access: 'read_write'},
      {name: 'rows', view: rows, type: 'f32', access: 'read_write'}
    ],
    body: 'distribution[distributionOffset + index] = initial[initialOffset + index]; if(index < 11u){counts[countsOffset+index]=8.0;} if(index==0u){rows[rowsOffset+40u]=8.0;}'
  });
  await execute([prepare, finish]);
  const table = await read(output.table);
  // Ten identical draws: population variance is exactly zero, >= counts every tie.
  for (const base of [0, 6]) {
    expect(table[base]).toBe(Math.fround(0.1));
    expect(table[base + 1]).toBe(1);
    expect(table[base + 2]).toBe(10);
    expect(table[base + 3]).toBe(Math.fround(0.1));
    expect(table[base + 4]).toBe(0);
    expect(table[base + 5]).toBeNaN();
  }
}

export async function checkZeroBudget(
  harness: Harness,
  execute: ReviewExecution,
  read: Harness['read']
) {
  const {nodes, output, parameters} = createReviewNonstationarity(harness, 2);
  await execute(nodes);
  expect((await read(output.standardDeviations)).slice(2).every(Number.isFinite)).toBe(true);
  const raw = getGPUPermutationParameterValues({seed: 12345, permutationCount: 2});
  raw[2] = 0;
  harness.set(parameters, raw);
  await execute(nodes);
  expect((await read(output.standardDeviations)).slice(0, 2)).toEqual([0, 0]);
  expect((await read(output.standardDeviations)).slice(2).every(Number.isNaN)).toBe(true);
  const table = await read(output.table);
  for (const base of [0, 6]) {
    expect(table[base]).toBe(0);
    for (let field = 1; field < 6; field++) expect(table[base + field]).toBeNaN();
  }
}

export async function checkZeroBudgetStages(
  harness: Harness,
  execute: ReviewExecution,
  read: Harness['read']
) {
  const {port, graph} = harness;
  const {nodes, output, parameters} = createReviewNonstationarity(harness, 2);
  const merge = nodes.find(node => node.id.endsWith('-batch-0-merge'))!;
  const finish = nodes.find(node => node.id.endsWith('-finish'))!;
  const partial = harness.record(merge).bindings.find(binding => binding.name === 'partial')!.view;
  const rows = harness.record(finish).bindings.find(binding => binding.name === 'rows')!.view;
  // Closed-form moments of eight coefficients: observed all equal, simulated deviations
  // alternating +/-1 or +/-2. One tile, three runs, five moment channels, then batch cursor.
  const initial = port('float32', [8, 0, 0, 0, 0, 8, 0, 0, 8, 32, 8, 0, 0, 32, 8, 0]);
  const prepare = createWGSLKernelNode(graph, {
    id: 'review-zero-prepare',
    operation: 'GWRReview',
    invocationCount: 16,
    bindings: [
      {name: 'initial', view: initial, type: 'f32', access: 'read'},
      {name: 'partial', view: partial, type: 'f32', access: 'read_write'},
      {name: 'rows', view: rows, type: 'f32', access: 'read_write'}
    ],
    body: 'partial[partialOffset + index] = initial[initialOffset + index]; if(index==0u){rows[rowsOffset+40u]=8.0;}'
  });
  const stages = [prepare, merge, finish];
  await execute(stages);
  expect(await read(output.standardDeviations)).toEqual([0, 0, 1, 2, 2, 1]);
  const raw = getGPUPermutationParameterValues({seed: 12345, permutationCount: 2});
  raw[2] = 0;
  harness.set(parameters, raw);
  await execute(stages);
  const distribution = await read(output.standardDeviations);
  expect(distribution).toEqual([0, 0, NaN, NaN, NaN, NaN]);
  const table = await read(output.table);
  for (const base of [0, 6])
    for (let field = 1; field < 6; field++) expect(table[base + field]).toBeNaN();
}

export async function checkConstantStatistics(
  harness: Harness,
  execute: ReviewExecution,
  read: Harness['read']
) {
  const {port, graph} = harness;
  const summary = port('float32', [0, 0, 0, -999, 10, 1, 0, 0, 0, 0, 0, 10]);
  const nodes = new GPUGeographicallyWeightedRegression({
    positions: port('float32x2', Array(20).fill(0)),
    predictors: port('float32', Array(10).fill(1)),
    predictorCount: 1,
    response: port('float32', Array(10).fill(0.1)),
    parameters: port('float32', [0, 0, 1, 0, 3]),
    maximumBandwidthCount: 1,
    indexGridSize: false,
    output: {summary, coefficients: port('float32', Array(20).fill(0))}
  }).getCommandNodes(graph);
  const statistics = nodes.find(node => node.id.endsWith('-tile-statistics'))!;
  const rowValid = harness
    .record(statistics)
    .bindings.find(binding => binding.name === 'rowValid')!.view;
  const tileStatistics = harness
    .record(statistics)
    .bindings.find(binding => binding.name === 'tileStatistics')!.view;
  const moments = port('float32', [-999, -999, -999]);
  const prepare = createWGSLKernelNode(graph, {
    id: 'review-constant-prepare',
    operation: 'GWRReview',
    invocationCount: 10,
    bindings: [{name: 'rowValid', view: rowValid, type: 'u32', access: 'read_write'}],
    body: 'rowValid[rowValidOffset+index]=1u;rowValid[rowValidOffset+10u+index*6u+4u]=0u;'
  });
  const copy = createWGSLKernelNode(graph, {
    id: 'review-constant-copy',
    operation: 'GWRReview',
    invocationCount: 3,
    bindings: [
      {name: 'statistics', view: tileStatistics, type: 'f32', access: 'read'},
      {name: 'moments', view: moments, type: 'f32', access: 'read_write'}
    ],
    body: 'moments[momentsOffset+index]=statistics[statisticsOffset+index];'
  });
  await execute([prepare, statistics, copy, nodes.find(node => node.id.endsWith('-summarize'))!]);
  expect(await read(moments)).toEqual([10, Math.fround(0.1), 0]);
  expect((await read(summary))[3]).toBeNaN();
}

export async function checkEmptyFirstConstantReduction(
  harness: Harness,
  execute: ReviewExecution,
  read: Harness['read'],
  realReductions = false
) {
  const {port, graph} = harness;
  const statistics = port('float32', [
    0,
    0,
    0,
    ...Array.from({length: 13}, () => [1, 0.1, 0]).flat()
  ]);
  const summary = port('float32', [0, 0, 0, -999, 13, 1, 0, 0, 0, 0, 0, 13]);
  const nodes = createGWRVarianceReductionNodes(graph, {
    id: 'review-empty-first',
    tileCount: 14,
    statistics,
    summary
  });
  const centre = nodes.find(node => node.id.endsWith('-variance-centre'))!;
  const squares = nodes.find(node => node.id.endsWith('-variance-squares'))!;
  const finish = nodes.find(node => node.id.endsWith('-summarize'))!;
  const find = (node: GPUCommandNode, name: string) =>
    harness.record(node).bindings.find(binding => binding.name === name)!.view;
  const count = find(squares, 'totalCount'),
    deviation = find(squares, 'totalDeviation'),
    totalSquares = find(finish, 'totalSquares');
  const moments = port('float32', [-999, -999, -999]);
  const copy = createWGSLKernelNode(graph, {
    id: 'review-empty-copy',
    operation: 'GWRReview',
    invocationCount: 1,
    bindings: [
      {name: 'count', view: count, type: 'f32', access: 'read'},
      {name: 'deviation', view: deviation, type: 'f32', access: 'read'},
      {name: 'squares', view: totalSquares, type: 'f32', access: 'read'},
      {name: 'moments', view: moments, type: 'f32', access: 'read_write'}
    ],
    body: 'moments[momentsOffset]=count[countOffset];moments[momentsOffset+1u]=deviation[deviationOffset];moments[momentsOffset+2u]=squares[squaresOffset];'
  });
  if (realReductions) await execute([...nodes, copy]);
  else {
    // Replay the real scalar moment kernels. The published workgroup reductions are exercised
    // by the headless twin; this small serial sum only supplies their independent scalar inputs.
    const firstTile = harness
      .record(centre)
      .bindings.find(binding => binding.name === 'firstTile')?.view;
    const prepare = firstTile
      ? [
          createWGSLKernelNode(graph, {
            id: 'review-empty-anchor',
            operation: 'GWRReview',
            invocationCount: 1,
            bindings: [{name: 'firstTile', view: firstTile, type: 'f32', access: 'read_write'}],
            body: 'firstTile[firstTileOffset]=1.0;'
          })
        ]
      : [];
    const reduce = (suffix: string, source: GraphDataView, destination: GraphDataView) =>
      createWGSLKernelNode(graph, {
        id: `review-empty-reduce-${suffix}`,
        operation: 'GWRReview',
        invocationCount: 1,
        bindings: [
          {name: 'sourceValues', view: source, type: 'f32', access: 'read'},
          {name: 'total', view: destination, type: 'f32', access: 'read_write'}
        ],
        body: 'var value=0.0;for(var slot=0u;slot<14u;slot++){value+=sourceValues[sourceValuesOffset+slot];}total[totalOffset]=value;'
      });
    await execute([
      ...prepare,
      centre,
      reduce('count', find(centre, 'counts'), count),
      reduce('mean', find(centre, 'deviations'), deviation),
      squares,
      reduce('squares', find(squares, 'squares'), totalSquares),
      finish,
      copy
    ]);
  }
  // Thirteen identical nonzero means, each with count one and within-tile M2 zero; an empty
  // leading tile cannot introduce a direction or nonzero variance. RSS=0 still has undefined R2.
  expect(await read(moments)).toEqual([13, 0, 0]);
  expect((await read(summary))[3]).toBeNaN();
}
