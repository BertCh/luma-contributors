import {expect, test, vi} from 'vitest';
import * as arrow from 'apache-arrow';
import {cellToBoundary} from 'h3-js';
import {writeWKB} from '@math.gl/geospatial';
import {convertGeoArrowVectorToDenseUnion} from '@luma.gl/graph/arrow';
import {KeplerDatasetRegistry} from '../src/runtime/dataset-registry';
import {
  readResidentSelectedGeometry,
  type ResidentSelectedGeometryRequest
} from '../../../examples/deck/kepler-compute/src/resident-select-geometry';
import oracle from './selected-geometry-native-oracle.json';

function register(
  table: arrow.Table,
  registry = new KeplerDatasetRegistry({memoryBudgetBytes: 1024 * 1024})
) {
  let offset = 0;
  const snapshot = registry.registerDataset({
    id: 'source',
    value: {},
    source: {kind: 'arrow', value: table},
    batches: table.batches.map((batch, index) => {
      const descriptor = {
        id: `original-${index}`,
        rowCount: batch.numRows,
        sourceRowOffset: offset
      };
      offset += batch.numRows;
      return descriptor;
    }),
    resources: []
  });
  const request: ResidentSelectedGeometryRequest = {
    registry,
    datasetId: snapshot.id,
    revision: snapshot.revision,
    sourceRowIndex: 0,
    kind: 'geojson',
    column: 'geometry',
    featureId: 'fresh-editor-id',
    maximumPayloadBytes: 8192
  };
  return {registry, request};
}
function tableWithEncoding(vector: arrow.Vector, encoding: string): arrow.Table {
  const table = new arrow.Table({geometry: vector});
  table.schema.fields[0].metadata.set('ARROW:extension:name', encoding);
  return table;
}

test('Select Geometry preserves pinned native first-FeatureCollection semantics and source identity', async () => {
  // Oracle generated by executing the installed pinned parseGeoJsonRawFeature and
  // featureFromGeometry functions with their actual @mapbox/geojson-normalize dependency.
  const first = arrow.vectorFromArray([null, JSON.stringify(oracle[0].input)], new arrow.Utf8());
  const empty = arrow.makeData({
    type: new arrow.Utf8(),
    length: 0,
    valueOffsets: new Int32Array([0]),
    data: new Uint8Array()
  });
  const last = arrow.vectorFromArray([JSON.stringify(oracle[1].input)], new arrow.Utf8());
  const table = new arrow.Table({geometry: new arrow.Vector([...first.data, empty, ...last.data])});
  const {request} = register(table);
  const result = await readResidentSelectedGeometry({...request, sourceRowIndex: 1});
  expect(result.status).toBe('ready');
  if (result.status !== 'ready') throw new Error(result.reason);
  expect(result.feature).toEqual({...oracle[0].expected, id: 'fresh-editor-id'});
  expect(result.source).toMatchObject({
    datasetId: 'source',
    revision: 1,
    batchId: 'original-0',
    sourceRowIndex: 1
  });
  expect(result.payloadByteLength).toBe(
    new TextEncoder().encode(JSON.stringify(result.feature)).length
  );
  expect(result.isCurrent()).toBe(true);
  result.feature.properties!['name'] = 'editor mutation';
  const retained = table.getChild('geometry')!.get(1);
  if (typeof retained !== 'string') throw new Error('Missing retained GeoJSON');
  expect(JSON.parse(retained).features[0].properties.name).toBe('first');
  const polygon = await readResidentSelectedGeometry({...request, sourceRowIndex: 2});
  expect(polygon.status === 'ready' && polygon.feature).toEqual({
    ...oracle[1].expected,
    id: 'fresh-editor-id'
  });
  expect((await readResidentSelectedGeometry(request)).status).toBe('unsupported');
});

test('dictionary preflight inspects only the selected logical value despite oversized other rows', async () => {
  const feature = {type: 'Point', coordinates: [1, 2]};
  const dictionary = new arrow.Dictionary(new arrow.Utf8(), new arrow.Int32());
  const table = new arrow.Table({
    geometry: arrow.vectorFromArray(['x'.repeat(200000), JSON.stringify(feature)], dictionary)
  });
  const {request} = register(table);
  const result = await readResidentSelectedGeometry({
    ...request,
    sourceRowIndex: 1,
    maximumPayloadBytes: 512
  });
  expect(result.status === 'ready' && result.feature.geometry).toEqual(feature);
  expect((await readResidentSelectedGeometry({...request, maximumPayloadBytes: 512})).status).toBe(
    'budget-exceeded'
  );
});

test('H3 selection uses exact retained identity and canonical raw boundary rather than display coverage', async () => {
  const cell = '877eb5722ffffff';
  const {request} = register(
    new arrow.Table({geometry: arrow.vectorFromArray([BigInt(`0x${cell}`)], new arrow.Uint64())})
  );
  const result = await readResidentSelectedGeometry({...request, kind: 'hexagonId'});
  expect(result.status).toBe('ready');
  if (result.status !== 'ready') throw new Error(result.reason);
  expect(result.feature).toEqual({
    type: 'Feature',
    id: 'fresh-editor-id',
    properties: {isClosed: true},
    geometry: {type: 'Polygon', coordinates: [cellToBoundary(cell, true)]}
  });
  const numeric = register(
    new arrow.Table({geometry: arrow.makeVector(new Float64Array([Number(BigInt(`0x${cell}`))]))})
  );
  expect(await readResidentSelectedGeometry({...numeric.request, kind: 'hexagonId'})).toMatchObject(
    {status: 'unsupported'}
  );
});

test('reads one sliced native Arrow XYZ geometry and preserves source null slots', async () => {
  // GeoArrow names the coordinate child after its dimension. Since @luma.gl 10.0.0-alpha.12 the
  // published adapter refuses a three-component child with any other name, because xyz and xym
  // cannot be told apart (see the test below).
  const coordinate = new arrow.FixedSizeList(3, new arrow.Field('xyz', new arrow.Float64(), false));
  const line = new arrow.List(new arrow.Field('vertices', coordinate, false));
  const backing = arrow.vectorFromArray(
    [
      [[99, 99, 99]],
      null,
      [
        [1, 2, 3],
        [4, 5, 6]
      ],
      [[77, 77, 77]]
    ],
    line
  );
  const table = tableWithEncoding(backing.slice(1, 3), 'geoarrow.linestring');
  const {request} = register(table);
  const result = await readResidentSelectedGeometry({...request, sourceRowIndex: 1});
  expect(result.status === 'ready' && result.feature.geometry).toEqual({
    type: 'LineString',
    coordinates: [
      [1, 2, 3],
      [4, 5, 6]
    ]
  });
  expect((await readResidentSelectedGeometry(request)).status).toBe('unsupported');
  const separated = new arrow.Struct([
    new arrow.Field('x', new arrow.Float64()),
    new arrow.Field('y', new arrow.Float64()),
    new arrow.Field('z', new arrow.Float64())
  ]);
  const separatedSource = register(
    tableWithEncoding(arrow.vectorFromArray([{x: 1, y: 2, z: 3}], separated), 'geoarrow.point')
  );
  const point = await readResidentSelectedGeometry(separatedSource.request);
  expect(point.status === 'ready' && point.feature.geometry).toEqual({
    type: 'Point',
    coordinates: [1, 2, 3]
  });
});

test('raw WKB and explicitly decoded union rows retain their native geometry identity', async () => {
  const geometry = {
    type: 'MultiPoint' as const,
    coordinates: [
      [1, 2],
      [3, 4]
    ]
  };
  const binary = arrow.vectorFromArray([new Uint8Array(writeWKB(geometry))], new arrow.Binary());
  const raw = register(tableWithEncoding(binary, 'geoarrow.wkb'));
  const result = await readResidentSelectedGeometry(raw.request);
  expect(result.status === 'ready' && result.feature.geometry).toEqual(geometry);
  const decoded = register(
    tableWithEncoding(convertGeoArrowVectorToDenseUnion(binary), 'geoarrow.geometry')
  );
  const union = await readResidentSelectedGeometry(decoded.request);
  expect(union.status === 'ready' && union.feature.geometry).toEqual(geometry);
});

test('rejects oversized UTF8 and nested Arrow cells before decoding or materialization', async () => {
  const text = JSON.stringify({
    type: 'Feature',
    properties: {large: 'a'.repeat(20000)},
    geometry: {type: 'Point', coordinates: [1, 2]}
  });
  const table = new arrow.Table({geometry: arrow.vectorFromArray([text], new arrow.Utf8())});
  const {request} = register(table);
  const column = table.getChild('geometry')!;
  const row = column.slice(0, 1);
  vi.spyOn(table, 'getChild').mockReturnValue(column);
  vi.spyOn(column, 'slice').mockReturnValue(row);
  const get = vi.spyOn(row, 'get');
  const parse = vi.spyOn(JSON, 'parse');
  const decode = vi.spyOn(TextDecoder.prototype, 'decode');
  const result = await readResidentSelectedGeometry({...request, maximumPayloadBytes: 128});
  expect(result.status).toBe('budget-exceeded');
  expect(get).not.toHaveBeenCalled();
  expect(parse).not.toHaveBeenCalled();
  expect(decode).not.toHaveBeenCalled();
  vi.restoreAllMocks();
  const coordinate = new arrow.FixedSizeList(
    2,
    new arrow.Field('value', new arrow.Float64(), false)
  );
  const line = new arrow.List(new arrow.Field('vertices', coordinate, false));
  const nested = register(
    tableWithEncoding(
      arrow.vectorFromArray([Array.from({length: 5000}, (_, index) => [index, 0])], line),
      'geoarrow.linestring'
    )
  );
  expect(
    (await readResidentSelectedGeometry({...nested.request, maximumPayloadBytes: 1024})).status
  ).toBe('budget-exceeded');
  expect(
    (
      await readResidentSelectedGeometry({
        ...nested.request,
        maximumPayloadBytes: 1024 * 1024,
        maximumVertices: 4
      })
    ).status
  ).toBe('budget-exceeded');
});

test('source leases prevent stale publication and release retired storage after the bounded read', async () => {
  const table = new arrow.Table({
    geometry: arrow.vectorFromArray(
      [JSON.stringify({type: 'Point', coordinates: [1, 2]})],
      new arrow.Utf8()
    )
  });
  const {registry, request} = register(table);
  const destroy = vi.fn();
  const leased = registry.registerDataset({
    id: 'source',
    value: {},
    source: {kind: 'arrow', value: table},
    batches: [{id: 'retained', rowCount: 1}],
    resources: [
      {
        id: 'retained-source',
        value: {},
        byteLength: 8,
        memoryKind: 'cpu',
        ownership: 'owned',
        destroy
      }
    ]
  });
  const currentRequest = {...request, revision: leased.revision};
  const read = readResidentSelectedGeometry(currentRequest);
  const replacement = register(table, registry);
  expect(destroy).not.toHaveBeenCalled();
  expect(await read).toMatchObject({status: 'stale'});
  expect(destroy).toHaveBeenCalledTimes(1);
  expect(await readResidentSelectedGeometry(currentRequest)).toMatchObject({status: 'stale'});
  const current = await readResidentSelectedGeometry(replacement.request);
  expect(current.status).toBe('ready');
  register(table, registry);
  expect(current.status === 'ready' && current.isCurrent()).toBe(false);
  expect(registry.memoryUsage.totalBytes).toBe(0);
});

test('unsupported encoding, nongeographic CRS, invalid row and empty editor IDs fail explicitly', async () => {
  const table = tableWithEncoding(
    arrow.vectorFromArray(['POINT (1 2)'], new arrow.Utf8()),
    'geoarrow.wkt'
  );
  const {request} = register(table);
  expect(await readResidentSelectedGeometry(request)).toMatchObject({status: 'unsupported'});
  table.schema.fields[0].metadata.set(
    'ARROW:extension:metadata',
    JSON.stringify({crs: 'EPSG:3857'})
  );
  expect(await readResidentSelectedGeometry(request)).toMatchObject({
    status: 'unsupported',
    reason: expect.stringContaining('longitude/latitude')
  });
  expect((await readResidentSelectedGeometry({...request, sourceRowIndex: -1})).status).toBe(
    'unsupported'
  );
  expect((await readResidentSelectedGeometry({...request, featureId: ''})).status).toBe(
    'unsupported'
  );
});

test('reports an unnamed three-component coordinate child as unsupported', async () => {
  const coordinate = new arrow.FixedSizeList(
    3,
    new arrow.Field('value', new arrow.Float64(), false)
  );
  const line = new arrow.List(new arrow.Field('vertices', coordinate, false));
  const vector = arrow.vectorFromArray(
    [
      [
        [1, 2, 3],
        [4, 5, 6]
      ]
    ],
    line
  );
  const {request} = register(tableWithEncoding(vector, 'geoarrow.linestring'));
  const result = await readResidentSelectedGeometry(request);
  expect(result.status).toBe('unsupported');
  expect(result.status === 'unsupported' && result.reason).toMatch(
    /Ambiguous three-component coordinates/
  );
});
