// Prints a static metadata module; callers review/apply the output. No runtime source-file reads.
import typescript from 'typescript';
import {readFileSync, readdirSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const sourceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../modules/analysis/src');
const names = new Set();
for (const path of [
  'gpu-spatial-analysis/ontology/spatial-analysis-catalog.ts',
  'gpu-spatial-analysis/ontology/kepler-analysis-catalog.ts',
  'gpu-spatial-analysis/ontology/coverage-expansion-catalog.ts',
  'gpu-spatial-analysis/spatial-validation/spatial-validation-descriptors.ts'
]) {
  const source = typescript.createSourceFile(
    path,
    readFileSync(join(sourceRoot, path), 'utf8'),
    typescript.ScriptTarget.Latest,
    true
  );
  function visit(node) {
    if (
      typescript.isPropertyAssignment(node) &&
      node.name.getText(source) === 'operators' &&
      typescript.isArrayLiteralExpression(node.initializer)
    ) {
      for (const element of node.initializer.elements)
        if (typescript.isStringLiteral(element)) names.add(element.text);
    }
    typescript.forEachChild(node, visit);
  }
  visit(source);
}
const summaries = new Map();
function readDeclarations(directory) {
  for (const entry of readdirSync(directory, {withFileTypes: true})) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) readDeclarations(path);
    else if (entry.name.endsWith('.ts')) {
      const source = typescript.createSourceFile(
        path,
        readFileSync(path, 'utf8'),
        typescript.ScriptTarget.Latest,
        true
      );
      for (const declaration of source.statements) {
        if (
          !(
            typescript.isClassDeclaration(declaration) ||
            typescript.isFunctionDeclaration(declaration)
          ) ||
          !declaration.name ||
          !names.has(declaration.name.text) ||
          !declaration.jsDoc?.length
        )
          continue;
        // Visibility has two entry-point implementations; the original record is spatial.
        if (
          declaration.name.text === 'addVisibilityGraphRecipe' &&
          !path.includes('/gpu-spatial-analysis/')
        )
          continue;
        const paragraph = declaration.jsDoc
          .at(-1)
          .getText(source)
          .replace(/^\/\*\*|\*\/$/g, '')
          .replace(/^\s*\* ?/gm, '')
          .trim()
          .split(/\n\s*\n/)[0]
          .replace(/\{@link\s+([^}\s]+)(?:\s+([^}]+))?\}/g, (_, name, label) => label || name)
          .replace(/\s+/g, ' ')
          .trim();
        if (!paragraph || paragraph.startsWith('@')) continue;
        const sentence = paragraph.match(/^.*?[.!?](?=\s+[A-Z]|$)/)?.[0] ?? paragraph;
        if (!summaries.has(declaration.name.text)) summaries.set(declaration.name.text, sentence);
      }
    }
  }
}
readDeclarations(sourceRoot);
// Editorial descriptions where the class has no TSDoc or its opening is chiefly provenance.
summaries.set(
  'GPUNormalizeGeometry',
  'Normalizes points, lines, rings, polygons, multis and nested collections without flattening their structure.'
);
summaries.set(
  'GPURankMarkov',
  'Full-rank and geographic-rank transition matrices over common complete cases, with stable sorted ranking.'
);
summaries.set(
  'GPUSpatialPredicateJoin',
  'Produces compact matching feature-row pairs for spatial predicates, with exact refinement and capacity status.'
);
const missing = [...names].filter(name => !summaries.has(name));
if (missing.length) throw new Error(`Missing summaries: ${missing.join(', ')}`);
console.log(`// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: Copyright (c) vis.gl contributors

// Generated by scripts/generate-spatial-catalog-summaries.mjs from public TSDoc plus editorial overrides.
// Kept static so discovery imports neither constructors nor filesystem tools.
export const SPATIAL_ANALYSIS_OPERATOR_SUMMARIES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries([...names].sort().map(name => [name, summaries.get(name)])), null, 2)};
`);
